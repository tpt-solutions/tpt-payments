// Endpoint represents an API endpoint with compatibility status
type Endpoint struct {
	Method   string `json:"method"`
	Path     string `json:"path"`
	Status   string `json:"status"` // "implemented", "partial", "missing"
	Coverage int    `json:"coverage"`
	Notes    string `json:"notes,omitempty"`
}

// CompatibilityReport holds full Stripe compatibility analysis
type CompatibilityReport struct {
	GeneratedAt     time.Time  `json:"generated_at"`
	APIVersion      string     `json:"api_version"`
	TargetStripe    string     `json:"target_stripe_version"`
	TotalEndpoints  int        `json:"total_endpoints"`
	Implemented     int        `json:"implemented"`
	Partial         int        `json:"partial"`
	Missing         int        `json:"missing"`
	CoveragePercent float64    `json:"coverage_percent"`
	Endpoints       []Endpoint `json:"endpoints"`
	TestsPassed     int        `json:"tests_passed"`
	TestsFailed     int        `json:"tests_failed"`
}

