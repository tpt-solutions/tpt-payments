const markdownTemplate = `# Stripe API Compatibility Report

**Generated:** {{.GeneratedAt.Format "January 02, 2006 15:04:05 UTC"}}
**API Version:** {{.APIVersion}}
**Target Stripe Version:** {{.TargetStripe}}

## Summary

| Metric | Value |
|--------|-------|
| Total Endpoints | {{.TotalEndpoints}} |
| ✅ Implemented | {{.Implemented}} |
| ⚠️ Partial | {{.Partial}} |
| ❌ Missing | {{.Missing}} |
| **Coverage** | **{{printf "%.1f" .CoveragePercent}}%** |

## Endpoint Compatibility

| Status | Method | Path | Coverage | Notes |
|--------|--------|------|----------|-------|
{{range .Endpoints}}| {{if eq .Status "implemented"}}✅{{else if eq .Status "partial"}}⚠️{{else}}❌{{end}} | {{.Method}} | ` + "`" + `{{.Path}}` + "`" + ` | {{.Coverage}}% | {{.Notes}} |
{{end}}

---

*Report generated by TPT Payments Compatibility Checker*
`

func generateReport() CompatibilityReport {
	implemented := 0
	partial := 0
	missing := 0
	totalCoverage := 0

	for _, ep := range stripeEndpoints {
		totalCoverage += ep.Coverage
		switch ep.Status {
		case "implemented":
			implemented++
		case "partial":
			partial++
		case "missing":
			missing++
		}
	}

	return CompatibilityReport{
		GeneratedAt:     time.Now().UTC(),
		APIVersion:      "v1",
		TargetStripe:    "2024-06-20",
		TotalEndpoints:  len(stripeEndpoints),
		Implemented:     implemented,
		Partial:         partial,
		Missing:         missing,
		CoveragePercent: float64(totalCoverage) / float64(len(stripeEndpoints)),
		Endpoints:       stripeEndpoints,
	}
}

func generateMarkdown(report CompatibilityReport) []byte {
	tmpl, err := template.New("report").Parse(markdownTemplate)
	if err != nil {
		panic(err)
	}

	var buf []byte
	w := &bufferWriter{&buf}
	err = tmpl.Execute(w, report)
	if err != nil {
		panic(err)
	}

	return buf
}

type bufferWriter struct {
	buf *[]byte
}

func (w *bufferWriter) Write(p []byte) (n int, err error) {
	*w.buf = append(*w.buf, p...)
	return len(p), nil
}

func main() {
	outputFormat := flag.String("format", "markdown", "Output format: markdown, json")
	outputFile := flag.String("output", "", "Output file path")
	threshold := flag.Float64("threshold", 70.0, "Coverage threshold for pass/fail")
	flag.Parse()

	report := generateReport()

	var output []byte
	var err error

	switch *outputFormat {
	case "json":
		output, err = json.MarshalIndent(report, "", "  ")
	case "markdown":
		output = generateMarkdown(report)
	default:
		fmt.Printf("Invalid format: %s\n", *outputFormat)
		os.Exit(1)
	}

	if err != nil {
		fmt.Printf("Error generating report: %v\n", err)
		os.Exit(1)
	}

	if *outputFile != "" {
		err = os.WriteFile(*outputFile, output, 0644)
		if err != nil {
			fmt.Printf("Error writing file: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("✅ Compatibility report written to %s\n", *outputFile)
	} else {
		fmt.Println(string(output))
	}

	fmt.Printf("\nTotal Compatibility: %.1f%%\n", report.CoveragePercent)

	// Exit with non-zero if coverage is below threshold
	if report.CoveragePercent < *threshold {
		fmt.Printf("\n❌ FAILED: Coverage %.1f%% below %.1f%% threshold\n", report.CoveragePercent, *threshold)
		os.Exit(1)
	}

	fmt.Printf("\n✅ PASSED: Coverage %.1f%% meets threshold\n", report.CoveragePercent)
}